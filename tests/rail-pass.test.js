'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const context = { console: { log() {}, error() {}, warn() {} }, module: undefined, Math };
vm.createContext(context);
for (const file of ['js/constants.js', 'js/utils.js', 'js/types.js', 'js/train-data.js', 'js/trainData.js', 'js/npcData.js', 'js/maps.js', 'js/story.js', 'js/items.js', 'js/moves.js', 'js/train.js', 'js/player.js', 'js/map.js', 'js/world-maps.js']) {
  vm.runInContext(fs.readFileSync(file, 'utf8'), context, { filename: file });
}
global.CONSTANTS = require('../js/constants.js');
global.NPC_DATA = vm.runInContext('NPC_DATA', context);
const Game = require('../js/game.js');
const maps = vm.runInContext('WORLD_MAPS', context);
const station = maps.PistonTown.npcs.find(npc => npc.type === 'station');
assert.ok(station, 'starting town has a station attendant');
const game = Object.create(Game.prototype);
game.currentMap = maps.PistonTown;
game.maps = maps;
game.player = { x: station.x, y: station.y - 1, direction: CONSTANTS.DIRECTIONS.DOWN, badges: [], storyFlags: {}, visitedMaps: ['PistonTown'] };
game.state = CONSTANTS.STATES.OVERWORLD;
game.dialogueBox = { show(lines, callback) { this.lines = lines; this.callback = callback; } };
game.input = { reset() {}, isKeyJustPressed() { return false; }, isVirtualKeyJustPressed() { return false; } };
game.audio = { playMusic() {} };
game.save = () => { game.saved = true; };
game.checkNPCInteraction();
assert.equal(game.state, CONSTANTS.STATES.DIALOGUE, 'rail pass remains locked before first badge');
game.player.badges.push('Harbor Badge');
game.checkNPCInteraction();
assert.equal(game.state, CONSTANTS.STATES.FAST_TRAVEL, 'badge unlocks station selection');
assert.deepEqual(Array.from(game.fastTravelDestinations), ['PistonTown']);
game.player.visitedMaps.push('CoalHarbor');
game.player.visitedMaps.push('City8');
game.refreshFastTravelDestinations();
assert.deepEqual(Array.from(game.fastTravelDestinations), ['PistonTown', 'CoalHarbor']);
game.beginFastTravel('CoalHarbor');
assert.equal(game.state, CONSTANTS.STATES.FAST_TRAVEL_TRANSITION);
game.updateFastTravelTransition(1);
assert.equal(game.player.currentMap, 'CoalHarbor');
assert.equal(game.currentMap, maps.CoalHarbor);
assert.equal(game.player.x, 10);
assert.equal(game.player.y, 12);
assert.equal(game.saved, true, 'arrival is saved');
assert.ok(game.player.visitedMaps.includes('CoalHarbor'));
const restored = vm.runInContext('Player.fromJSON(Player.prototype.toJSON.call(Object.assign(new Player(), { visitedMaps: ["PistonTown", "CoalHarbor"] })))', context);
assert.deepEqual(Array.from(restored.visitedMaps), ['PistonTown', 'CoalHarbor'], 'visited stations persist through save data');
console.log('Rail pass tests passed');
